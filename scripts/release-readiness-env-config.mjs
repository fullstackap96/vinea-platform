export const enabledFlagValues = new Set([
  'ENABLED',
  'PRODUCTION',
  'NON_PRODUCTION',
  'TRUE',
  '1',
  'YES',
  'ON',
])

export function getUnsafeReleaseRuntimeFlags(env) {
  const unsafeEnabledFlags = forbiddenEnabledRuntimeFlags
    .filter((name) => enabledFlagValues.has(String(env[name] ?? '').toUpperCase()))
    .map((name) => ({
      name,
      kind: 'enabled-runtime-flag',
      valueLabel: 'present-and-enabled',
    }))

  const unsafeConfiguredFlags = forbiddenConfiguredRuntimeResidueFlags
    .filter((name) => String(env[name] ?? '').trim().length > 0)
    .map((name) => ({
      name,
      kind: 'configured-runtime-residue',
      valueLabel: 'present-and-configured',
    }))

  return [...unsafeEnabledFlags, ...unsafeConfiguredFlags]
}
